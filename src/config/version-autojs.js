// =====================================================================
// 版本号：语义版本的唯一事实来源，手写维护
// =====================================================================
// 为什么要有这个文件：产品形态是 APK，装到设备上之后，从界面上根本看不出装的是哪一轮的包。
// 2026-09-24 在 rxfs 上就栽在这上面——代码改了一堆，设备上跑的还是六天前的包，
// 而界面、日志、应用信息三处都没有任何地方能把这件事说出来。
//
// 改它的时机：**每次打包给人用之前**，按这一轮做了什么把版本往上推一位，
// 并让 package.json 的 version 与它保持一致——两边不一致时
// build-autojs-project.js 直接拒绝生成项目，不会让人打出一个版本号说不清的包。
//
// 它会流到三个地方，显示的必须是同一个版本：
//   1. project.json 的 versionName -> APK 文件名与 Android 的应用信息
//   2. 菜单标题下面那行字（core/app-version-autojs.js 拼的）
//   3. 每次运行的 result.json 与日志头一行「构建版本」
//
// versionCode 不写在这里：它由 build-autojs-project.js 从 name 推
// （major*10000 + minor*100 + patch），少一个能对不上的地方。
//
// **新项目从模板生成出来时，这个数会被重置成 0.1.0**：新游戏的版本从头开始数，
// 继承模板的版本号只会让人以为这个游戏已经迭代过十几轮了。
// =====================================================================

